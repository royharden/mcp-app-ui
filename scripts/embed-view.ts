// Deterministically inline the built view into one HTML document and export it as a string
// module for createServer. Run after `vite build --config vite.view.config.ts`.
//
// Inputs:  view.html (template), dist/view/view.js (IIFE), dist/view/view.css, fixtures/approvals.v1.json
// Outputs: dist/view/view.html and server/generated/view-html.ts (gitignored; never handwritten)
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const distView = join(root, "dist", "view");

function fail(message: string): never {
  process.stderr.write(`embed-view: ${message}\n`);
  process.exit(1);
}

function read(path: string): string {
  if (!existsSync(path)) fail(`missing ${path}; run the view build first`);
  return readFileSync(path, "utf8");
}

const template = read(join(root, "view.html"));
const script = read(join(distView, "view.js"));
const cssFiles = readdirSync(distView).filter((f) => f.endsWith(".css"));
if (cssFiles.length > 1) fail(`expected at most one stylesheet, found ${cssFiles.join(", ")}`);
const style = cssFiles.length === 1 ? read(join(distView, cssFiles[0])) : "";

// An inline classic script ends at the first "</script", and "<!--" followed by "<script" can
// put the HTML parser into its escaped state. Rewrite all three sequences with an escape that
// means the same "<" inside string, template and regex literals (where a bundle has them). If
// one ever occurred in code position the bundle would fail to parse loudly in the exact-bundle
// harness, not silently.
// A preceding backslash would turn our escape into a different sequence; refuse that bundle.
if (/\\<(\/?script|!--)/i.test(script)) fail("bundle has a backslash before <script or <!--; escaping would change it");
const LT = "\\x3C";
const safeScript = script
  .replace(/<\/script/gi, `${LT}/script`)
  .replace(/<script/gi, `${LT}script`)
  .replace(/<!--/g, `${LT}!--`);
const safeStyle = style.replace(/<\/style/gi, "<\\/style");

for (const marker of ["/*__VIEW_STYLE__*/", "/*__VIEW_SCRIPT__*/"]) {
  if (template.split(marker).length !== 2) fail(`template must contain ${marker} exactly once`);
}
const html = template.replace("/*__VIEW_STYLE__*/", () => safeStyle).replace("/*__VIEW_SCRIPT__*/", () => safeScript);

// Check the template's own tags, not the bundle: minified React contains "<script>" text
// inside string literals, which is inert once the bundle sits inside one script element.
if ((template.match(/<script\b/gi) ?? []).length !== 1) fail("template must contain exactly one <script> element");
if (/<script\b[^>]*\b(src|type)\s*=/i.test(template)) fail("template script must be a classic inline script");
if (/<link\b[^>]*rel=["']?stylesheet/i.test(template)) fail("template must not reference external stylesheets");
if (/<\/script|<script|<!--/i.test(safeScript) || /<\/style/i.test(safeStyle)) fail("escaping failed");

const sha256Hex = (text: string) => createHash("sha256").update(text, "utf8").digest("hex");
const sha256B64 = (text: string) => createHash("sha256").update(text, "utf8").digest("base64");
const fixtureBytes = readFileSync(join(root, "fixtures", "approvals.v1.json"));

writeFileSync(join(distView, "view.html"), html, "utf8");
mkdirSync(join(root, "server", "generated"), { recursive: true });
const moduleText = [
  "// GENERATED by scripts/embed-view.ts from dist/view. Do not edit; do not commit.",
  `export const VIEW_HTML: string = ${JSON.stringify(html)};`,
  `export const VIEW_HTML_SHA256 = ${JSON.stringify(sha256Hex(html))};`,
  `export const VIEW_SCRIPT_SHA256_B64 = ${JSON.stringify(sha256B64(safeScript))};`,
  `export const VIEW_STYLE_SHA256_B64 = ${JSON.stringify(sha256B64(safeStyle))};`,
  `export const DATASET_SHA256 = ${JSON.stringify(createHash("sha256").update(fixtureBytes).digest("hex"))};`,
  "",
].join("\n");
writeFileSync(join(root, "server", "generated", "view-html.ts"), moduleText, "utf8");
process.stdout.write(`embed-view: ${html.length} chars, sha256 ${sha256Hex(html)}\n`);
